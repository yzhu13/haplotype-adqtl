"""
Phase 1 / Direction 1 — Step 3b: recover the actual TF symbol from the vignette table.

Background
----------
`p1_09_tf_motif_vignette.py` stored the top CHIP_TF track as a single composite
string, `bg_top_tf = "{biosample_name} / {track_name[:40]}"`, e.g.

    "K562 / EFO:0002067 TF ChIP-seq GATA1"

Downstream reading of that column picked up the leading *biosample* (cell line),
not the TF. The TF symbol was never lost, though: it sits inside `track_name`
right after the literal marker "TF ChIP-seq". This script parses it back out of
the existing `results/phase1/p1_tf_vignette.tsv` -- NO AlphaGenome API calls, no
re-scoring.

Caveat that cannot be fixed without a re-run: `track_name` was truncated to 40
characters when written. For a handful of rows with a long ontology id the TF
token sits flush against that boundary and may itself be clipped; those rows are
flagged in `bg_tf_truncated` rather than silently trusted.

Second caveat: only the single strongest CHIP_TF track per variant was kept, so
the per-track table needed to restrict the vignette to LCL/GM12878 tracks is not
recoverable from disk. Most top tracks come from non-lymphoid biosamples; see the
report for the LCL-track breakdown.

Inputs : results/phase1/p1_tf_vignette.tsv
Outputs: results/phase1/p1_tf_vignette_named.tsv
         docs/phase1_tf_vignette_report.md   (regenerated, TF symbols resolved)
"""
from pathlib import Path
import pandas as pd

BASE = Path(__file__).resolve().parents[1]
P1 = BASE / "results" / "phase1"
DOCS = BASE / "docs"

MARKER = " TF ChIP-seq "
TRACK_TRUNC_LEN = 40  # p1_09 wrote str(track_name)[:40]
# biosamples that are lymphoblastoid cell lines (the paper's tissue context)
LCL_BIOSAMPLES = {"GM12878", "GM15510", "GM23338", "GM12891", "GM12892"}


def parse_top_tf(s):
    """'K562 / EFO:0002067 TF ChIP-seq GATA1' -> (biosample, tf_symbol, truncated?, track)."""
    if not isinstance(s, str) or not s.strip():
        return pd.Series({"bg_biosample": None, "bg_tf_symbol": None,
                          "bg_tf_truncated": False, "bg_track_raw": None})
    # biosample names may themselves contain '/' (e.g. 'NT2/D1'), but only the
    # separator inserted by p1_09 is padded with spaces.
    if " / " in s:
        biosample, track = s.split(" / ", 1)
    else:
        biosample, track = None, s
    tf = None
    truncated = False
    if MARKER in track:
        tail = track.split(MARKER, 1)[1]
        parts = tail.split()
        if parts:
            tf = parts[0]
            # the token is the last thing on a maximally long track string ->
            # the 40-char cut may have landed inside the symbol itself
            truncated = (len(track) >= TRACK_TRUNC_LEN) and (len(parts) == 1)
    return pd.Series({"bg_biosample": biosample, "bg_tf_symbol": tf,
                      "bg_tf_truncated": truncated, "bg_track_raw": track})


def main():
    src = P1 / "p1_tf_vignette.tsv"
    df = pd.read_csv(src, sep="\t")
    parsed = df.bg_top_tf.apply(parse_top_tf)
    out = pd.concat([df, parsed], axis=1)
    dst = P1 / "p1_tf_vignette_named.tsv"
    out.to_csv(dst, sep="\t", index=False)
    print(f"[p1_09b] {len(out)} rows; TF symbol resolved for "
          f"{out.bg_tf_symbol.notna().sum()}; flagged truncated: "
          f"{int(out.bg_tf_truncated.sum())}")
    print(f"[p1_09b] wrote {dst}")

    log = []

    def L(s=""):
        log.append(s)
        try:
            print(s)
        except UnicodeEncodeError:
            print(s.encode("ascii", "replace").decode())

    bg = out.bg_chip_tf.dropna()
    fo = out.focal_chip_tf.dropna()
    n_lcl = out.bg_biosample.isin(LCL_BIOSAMPLES).sum()

    L("# Phase 1 / Direction 1 - TF-binding mechanism vignette (background SNPs)")
    L()
    L("_Regenerated by `scripts/p1_09b_parse_tf_names.py` from the existing")
    L("`p1_tf_vignette.tsv`. TF symbols are parsed out of the stored track name;")
    L("no new AlphaGenome API calls were made, so all scores are unchanged._")
    L()
    L(f"- confirmed cis-epistasis adQTLs scored: {len(out)}")
    L(f"- bg-SNP |CHIP_TF| median={bg.median():.3f}; focal |CHIP_TF| median={fo.median():.3f}")
    L(f"- bg-SNP |ATAC| median={out.bg_atac.median():.3f}")
    L(f"- top CHIP_TF track is from an LCL biosample in {n_lcl}/{len(out)} loci "
      f"({100 * n_lcl / len(out):.0f}%); the rest are non-lymphoid ENCODE biosamples")
    L()
    L("## Top vignettes: background SNPs with strong predicted TF-binding disruption")
    L()
    L("| gene | background SNP | \\|CHIP_TF\\| | \\|ATAC\\| | TF | biosample |")
    L("|---|---|---:|---:|---|---|")
    hi = out[out.bg_chip_tf > out.bg_chip_tf.median()].sort_values("bg_chip_tf", ascending=False)
    for _, r in hi.head(12).iterrows():
        tf = r.bg_tf_symbol or "?"
        if r.bg_tf_truncated:
            tf += " (name may be clipped)"
        L(f"| {r.ensemblID} | {r.best_bg} | {r.bg_chip_tf:.2f} | {r.bg_atac:.2f} "
          f"| **{tf}** | {r.bg_biosample} |")
    L()
    L("## TF symbols recurring across loci")
    L()
    vc = out.bg_tf_symbol.value_counts()
    L(", ".join(f"{k} ({v})" for k, v in vc[vc > 1].items()) or "_none recurring_")
    L()
    L("## Interpretation")
    L()
    L("- Background SNPs that modulate adQTL focal effects show predicted TF-binding/")
    L("  accessibility disruption => mechanism: an ancestry-differentiated background SNP")
    L("  alters a local TF site, changing the regulatory context and thus the focal")
    L("  variant's effect (cis-epistasis).")
    L()
    L("## Known limitations of this table")
    L()
    L("1. Only the single strongest CHIP_TF track per variant was retained by `p1_09`,")
    L("   and that track is usually from a **non-lymphoid** ENCODE biosample (K562,")
    L("   HepG2, HEK293, ...). Restricting the vignette to GM12878/LCL tracks would")
    L("   require re-running `p1_09_tf_motif_vignette.py` against the API.")
    L(f"2. `track_name` was truncated to {TRACK_TRUNC_LEN} characters at write time;")
    L("   rows flagged `bg_tf_truncated` in `p1_tf_vignette_named.tsv` may have a")
    L("   clipped TF symbol.")
    L("3. These are *predicted* binding disruptions, not measured ChIP.")

    rep = DOCS / "phase1_tf_vignette_report.md"
    rep.write_text("\n".join(log), encoding="utf-8")
    print(f"[p1_09b] wrote {rep}")


if __name__ == "__main__":
    main()
